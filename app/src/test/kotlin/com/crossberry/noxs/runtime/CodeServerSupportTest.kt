/*
 * Noxs — original implementation.
 * Unit tests for the pure-JVM code-server editor support logic: config
 * parsing, machine-status parsing, PID handling, port selection, the
 * WebView navigation policy, login injection and workspace resolution.
 */
package com.crossberry.noxs.runtime

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class CodeServerSupportTest {

    // ------------------------------------------------------------ config

    @Test
    fun `config parses bind addr auth and password`() {
        val yaml = """
            bind-addr: 127.0.0.1:8123
            auth: password
            cert: false
            password: s3cret-value-
        """.trimIndent()
        val cfg = CodeServerSupport.parseConfig(yaml)
        assertEquals("127.0.0.1:8123", cfg?.address)
        assertEquals(8123, cfg?.port)
        assertEquals("password", cfg?.auth)
        assertEquals("s3cret-value-", cfg?.password)
    }

    @Test
    fun `config without bind addr is rejected`() {
        assertNull(CodeServerSupport.parseConfig("auth: password\npassword: x"))
        assertNull(CodeServerSupport.parseConfig(""))
        assertNull(CodeServerSupport.parseConfig(null))
    }

    @Test
    fun `config with invalid port is rejected`() {
        assertNull(CodeServerSupport.parseConfig("bind-addr: 127.0.0.1:notaport"))
        assertNull(CodeServerSupport.parseConfig("bind-addr: 127.0.0.1:99999"))
        assertNull(CodeServerSupport.parseConfig("bind-addr: 127.0.0.1:0"))
    }

    @Test
    fun `config tolerates comments and blank lines`() {
        val cfg = CodeServerSupport.parseConfig(
            """
            # generated by noxs

            bind-addr: 127.0.0.1:8080
            auth: password
            """.trimIndent()
        )
        assertEquals(8080, cfg?.port)
        assertEquals("password", cfg?.auth)
        assertNull(cfg?.password)
    }

    // ------------------------------------------------------- status json

    @Test
    fun `status json parses the full document`() {
        val json = """
            prefix noise
            {"installed":true,"version":"4.89.1","running":true,"pid":4242,
             "port":8090,"http_ready":true,"address":"127.0.0.1:8090"}
            trailing noise
        """.trimIndent()
        val status = CodeServerSupport.parseStatusJson(json)
        assertEquals(true, status?.installed)
        assertEquals("4.89.1", status?.version)
        assertEquals(true, status?.running)
        assertEquals(4242L, status?.pid)
        assertEquals(8090, status?.port)
        assertEquals(true, status?.httpReady)
    }

    @Test
    fun `status json handles nulls and stopped state`() {
        val json = """{"installed":true,"version":"","running":false,"pid":null,"port":8080,"http_ready":false}"""
        val status = CodeServerSupport.parseStatusJson(json)
        assertEquals(true, status?.installed)
        assertEquals(null, status?.version)
        assertEquals(false, status?.running)
        assertEquals(null, status?.pid)
        assertEquals(8080, status?.port)
        assertEquals(false, status?.httpReady)
    }

    @Test
    fun `status json is null on garbage`() {
        assertNull(CodeServerSupport.parseStatusJson(null))
        assertNull(CodeServerSupport.parseStatusJson(""))
        assertNull(CodeServerSupport.parseStatusJson("no braces here"))
        assertNull(CodeServerSupport.parseStatusJson("{}"))
    }

    @Test
    fun `flat json get distinguishes keys from values`() {
        val json = """{"version":"version","installed":true,"note":"see \\"pid\\" below"}"""
        assertEquals("version", CodeServerSupport.flatJsonGet(json, "version"))
        assertEquals(true, CodeServerSupport.flatJsonGet(json, "installed")?.toBoolean())
    }

    // --------------------------------------------------------- pid / proc

    @Test
    fun `pid file parse accepts digits only`() {
        assertEquals(1234L, CodeServerSupport.parsePidFile("1234\n"))
        assertEquals(7L, CodeServerSupport.parsePidFile(" 7 "))
        assertNull(CodeServerSupport.parsePidFile(""))
        assertNull(CodeServerSupport.parsePidFile("12ab"))
        assertNull(CodeServerSupport.parsePidFile("-5"))
        assertNull(CodeServerSupport.parsePidFile(null))
        assertNull(CodeServerSupport.parsePidFile("1".repeat(13)))
    }

    @Test
    fun `cmdline matcher verifies code-server identity`() {
        assertTrue(
            CodeServerSupport.looksLikeCodeServerCmdline(
                "/opt/code-server/bin/code-server\u0000--config\u0000cfg".toByteArray()
            )
        )
        assertFalse(
            CodeServerSupport.looksLikeCodeServerCmdline("/bin/bash\u0000-l".toByteArray())
        )
        assertFalse(CodeServerSupport.looksLikeCodeServerCmdline(null))
        assertFalse(CodeServerSupport.looksLikeCodeServerCmdline(ByteArray(0)))
    }

    // --------------------------------------------------------------- port

    @Test
    fun `choose port keeps a free preferred port`() {
        assertEquals(8080, CodeServerSupport.choosePort(8080, isBusy = { false }))
    }

    @Test
    fun `choose port skips busy ports`() {
        val busy = setOf(8080, 8081, 8082)
        assertEquals(8083, CodeServerSupport.choosePort(8080, isBusy = { it in busy }))
    }

    @Test
    fun `choose port gives up after max attempts`() {
        assertNull(CodeServerSupport.choosePort(8080, isBusy = { true }, maxAttempts = 3))
    }

    // -------------------------------------------------- navigation policy

    @Test
    fun `editor url policy allows only the server origin`() {
        assertTrue(CodeServerSupport.isAllowedEditorUrl("http://127.0.0.1:8080/", 8080))
        assertTrue(CodeServerSupport.isAllowedEditorUrl("http://127.0.0.1:8080/?folder=/home/noxs", 8080))
        assertTrue(CodeServerSupport.isAllowedEditorUrl("http://localhost:8080/login", 8080))
        assertTrue(CodeServerSupport.isAllowedEditorUrl("about:blank", 8080))
    }

    @Test
    fun `editor url policy rejects everything else`() {
        assertFalse(CodeServerSupport.isAllowedEditorUrl("http://127.0.0.1:9999/", 8080))
        assertFalse(CodeServerSupport.isAllowedEditorUrl("https://127.0.0.1:8080/", 8080))
        assertFalse(CodeServerSupport.isAllowedEditorUrl("http://evil.example.com/", 8080))
        assertFalse(CodeServerSupport.isAllowedEditorUrl("javascript:alert(1)", 8080))
        assertFalse(CodeServerSupport.isAllowedEditorUrl("file:///etc/passwd", 8080))
        assertFalse(CodeServerSupport.isAllowedEditorUrl("data:text/html;base64,AAA", 8080))
        assertFalse(CodeServerSupport.isAllowedEditorUrl("not a url", 8080))
        assertFalse(CodeServerSupport.isAllowedEditorUrl("", 8080))
        assertFalse(CodeServerSupport.isAllowedEditorUrl(null, 8080))
    }

    @Test
    fun `login page detection`() {
        assertTrue(CodeServerSupport.isLoginPage("http://127.0.0.1:8080/login"))
        assertTrue(CodeServerSupport.isLoginPage("http://127.0.0.1:8080/login/"))
        assertTrue(CodeServerSupport.isLoginPage("http://127.0.0.1:8080/login?redirect=%2F"))
        assertFalse(CodeServerSupport.isLoginPage("http://127.0.0.1:8080/"))
        assertFalse(CodeServerSupport.isLoginPage("http://127.0.0.1:8080/loginz"))
        assertFalse(CodeServerSupport.isLoginPage(null))
    }

    @Test
    fun `login injection script carries only base64 payload`() {
        val b64 = "c2VjcmV0LXBhc3N3b3Jk" // base64("secret-password")
        val js = CodeServerSupport.loginInjectScript(b64)
        assertTrue(js.contains("atob('$b64')"))
        assertTrue(js.contains("input[type=password]"))
        assertTrue(js.contains("f.submit()"))
        // a hostile payload cannot break out of the quoted JS string: every
        // character outside the base64 alphabet is filtered away
        val hostile = CodeServerSupport.loginInjectScript("');alert(1)//")
        val extracted = Regex("atob\\('([^']*)'\\)").find(hostile)?.groupValues?.get(1)
        assertEquals("alert1", extracted)
        assertTrue(extracted!!.all { it in 'A'..'Z' || it in 'a'..'z' || it in '0'..'9' || it == '+' || it == '/' || it == '=' })
    }

    // ---------------------------------------------------------- workspace

    @Test
    fun `workspace prefers requested then cwd then home`() {
        val dirs = setOf("/home/noxs", "/home/noxs/work")
        val isDir = { p: String -> p in dirs }
        assertEquals(
            "/home/noxs/work",
            CodeServerSupport.resolveWorkspace("/home/noxs/work", "/home/noxs", "/home/noxs", isDir)
        )
        assertEquals(
            "/home/noxs",
            CodeServerSupport.resolveWorkspace("/gone", "/gone", "/home/noxs", isDir)
        )
        assertNull(CodeServerSupport.resolveWorkspace(null, null, "/gone", isDir))
    }

    @Test
    fun `workspace resolution preserves spaces and unicode`() {
        val dirs = setOf("/home/noxs/my projects/über folder")
        assertEquals(
            "/home/noxs/my projects/über folder",
            CodeServerSupport.resolveWorkspace(
                null, "/home/noxs/my projects/über folder", "/home/noxs"
            ) { it in dirs }
        )
    }

    @Test
    fun `guest workspace validation`() {
        assertTrue(CodeServerSupport.isValidGuestWorkspace("/home/noxs"))
        assertTrue(CodeServerSupport.isValidGuestWorkspace("/home/noxs/my project"))
        assertTrue(CodeServerSupport.isValidGuestWorkspace("/home/noxs/üñí/文件夹"))
        assertTrue(CodeServerSupport.isValidGuestWorkspace("/"))
        assertFalse(CodeServerSupport.isValidGuestWorkspace("home/noxs"))
        assertFalse(CodeServerSupport.isValidGuestWorkspace("/home/../etc"))
        assertFalse(CodeServerSupport.isValidGuestWorkspace("/home/noxs/\u0001"))
        assertFalse(CodeServerSupport.isValidGuestWorkspace(""))
        assertFalse(CodeServerSupport.isValidGuestWorkspace(null))
        assertFalse(CodeServerSupport.isValidGuestWorkspace("/" + "a".repeat(1100)))
    }
}
